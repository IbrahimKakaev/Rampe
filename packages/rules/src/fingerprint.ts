/**
 * Defect fingerprints, to follow a defect from one scan to the next.
 *
 * A fingerprint is the rule, the path of the page and the element's selector,
 * normalised so that changes around the defect leave it unchanged. axe-core
 * describes an element by its position when nothing else singles it out
 * ("img:nth-child(2)"), and frameworks generate class names that change at
 * every build ("css-a1b2c3"). Both are removed. Defects that become
 * indistinguishable are told apart by their order on the page.
 *
 * The trade-off: when one of two such defects is fixed, the remaining one
 * takes the first rank, so the comparison may name the wrong one of the two
 * as fixed. The counts stay right.
 */

/** Pseudo-classes that only say where an element sits among its siblings. */
const POSITIONAL =
  /:nth-(?:last-)?(?:child|of-type)\([^)]*\)|:(?:first|last|only)-(?:child|of-type)/g;

/** Class names and ids generated by tools, which change from one build to the next. */
const GENERATED_NAME = [
  // CSS-in-JS and scoped styles: emotion, styled-components, styled-jsx, Svelte, Astro, Angular.
  /^(?:css|sc|jsx|emotion|svelte|astro|ng-tns|ng-star)-[\w-]*$/,
  // A run of three digits or more: a database id, a counter.
  /\d{3,}/,
  // A short hash mixing letters and digits, such as "a1b2c3".
  /^(?=[a-z\d_-]*\d)(?=[a-z\d_-]*[a-z])[a-z\d]{5,}$/i,
];

/** Attributes added by frameworks to scope styles. */
const GENERATED_ATTRIBUTE = /\[(?:_ngcontent|_nghost|data-v|data-reactid)[^\]]*\]/g;

function isGenerated(name: string): boolean {
  return GENERATED_NAME.some((pattern) => pattern.test(name));
}

/** Normalises one compound selector, such as "div.css-a1b2c3.card:nth-child(2)". */
function normaliseCompound(compound: string): string {
  const withoutNoise = compound.replace(POSITIONAL, '').replace(GENERATED_ATTRIBUTE, '');
  const kept = withoutNoise.replace(
    /([.#])((?:\\.|[\w-])+)/g,
    (token: string, _sign: string, name: string) => {
      // CSS modules: "Button_root__x7Yz2" keeps "Button_root".
      const base = name.replace(/__[\w-]{5,}$/, '');
      return isGenerated(base) ? '' : token.replace(name, base);
    },
  );
  return kept === '' ? '*' : kept;
}

/** Normalises a selector as recorded by the scan: frames joined by " | ", shadow roots by " >>> ". */
export function normaliseSelector(selector: string): string {
  return selector
    .split(' | ')
    .map((frame) =>
      frame
        .split(' >>> ')
        .map((part) =>
          part
            .trim()
            // With a capture group, split() yields undefined where the group did not
            // match ("a b" gives ["a", undefined, "b"]); the standard types omit it.
            .split(/\s*([>+~])\s*|\s+/)
            .filter(
              (piece: string | undefined): piece is string => piece !== undefined && piece !== '',
            )
            .map((piece) => (/^[>+~]$/.test(piece) ? piece : normaliseCompound(piece)))
            .join(' '),
        )
        .join(' >>> '),
    )
    .join(' | ');
}

export interface PageDefect {
  readonly ruleId: string;
  readonly selector: string;
}

/**
 * Fingerprints the defects of a page, in the order the scan lists them.
 * The result has one fingerprint per defect, at the same index.
 */
export function fingerprintsOfPage(pageUrl: string, defects: readonly PageDefect[]): string[] {
  const path = new URL(pageUrl).pathname;
  const seen = new Map<string, number>();
  return defects.map(({ ruleId, selector }) => {
    const base = `${ruleId}|${path}|${normaliseSelector(selector)}`;
    const rank = (seen.get(base) ?? 0) + 1;
    seen.set(base, rank);
    return `${base}|${String(rank)}`;
  });
}
